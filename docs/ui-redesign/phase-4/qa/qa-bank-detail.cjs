const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 let errors=[];let checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 const check=(name,value)=>{assert.ok(value,name);checks.push(name)};
 await page.goto('http://127.0.0.1:8766/login');
 await page.locator('[name=username]').fill('qa_teacher');await page.locator('[name=password]').fill('Academy123!');
 await Promise.all([page.waitForURL(url=>!url.pathname.endsWith('/login')),page.locator('[type=submit]').click()]);
 for(const bank of [1,2,3,6]){
  await page.goto(`http://127.0.0.1:8766/question-banks/${bank}`);
  await page.waitForFunction(()=>document.querySelector('.bank-detail-page'));
  await page.waitForTimeout(350);
  check('bank '+bank+' loaded',await page.locator('h1').count()===1);
  const width=await page.evaluate(()=>({body:document.documentElement.scrollWidth, viewport:innerWidth}));
  check('bank '+bank+' desktop no page overflow',width.body<=width.viewport+1);
 }
 await page.goto('http://127.0.0.1:8766/question-banks/2');await page.waitForTimeout(300);
 const open=page.getByRole('button',{name:'Thêm câu hỏi',exact:true}).first();
 await open.click();
 const dialog=page.locator('#add-question-modal');await dialog.waitFor({state:'visible'});
 check('dialog opens native',await dialog.evaluate(el=>el.open));
 check('dialog focuses prompt',await page.locator('#manual-prompt').evaluate(el=>el===document.activeElement));
 await page.locator('#manual-prompt').fill('Tính $1+1$ và nêu kết quả.');
 await dialog.locator('[name=question_category]').fill('Phép cộng');
 for(let i=0;i<4;i++)await page.locator('#manual-option-'+i).fill(String(i+1));
 check('general save not curriculum-disabled',await dialog.locator('button[type=submit]').isEnabled());
 let controls=await dialog.locator('fieldset').evaluateAll(els=>els.filter(e=>e.querySelector('[name=option_text]')).map(e=>({disabled:e.disabled,count:e.querySelectorAll('[name=option_text]').length})));
 check('only active single choices submit',controls.filter(e=>!e.disabled).length===1);
 await dialog.locator('[name=question_type]').selectOption('true_false');
 controls=await dialog.locator('fieldset').evaluateAll(els=>els.filter(e=>e.querySelector('[name=option_text]')).map(e=>({disabled:e.disabled,count:e.querySelectorAll('[name=option_text]').length})));
 check('only active TF choices submit',controls.filter(e=>!e.disabled).length===1);
 await dialog.locator('[name=question_type]').selectOption('short_answer');
 await page.locator('#manual-short-answers').fill('2 | hai');await page.locator('#manual-short-mode').selectOption('text');
 await page.locator('[data-manual-preview-button]').click();
 check('short preview displays answers',(await page.locator('[data-manual-preview]').innerText()).includes('2 | hai'));
 await page.locator('#manual-question-image').setInputFiles({name:'wrong.pdf',mimeType:'application/pdf',buffer:Buffer.from('wrong')});
 check('image MIME custom error',await page.locator('#manual-question-image').evaluate(el=>!el.validity.valid));
 await page.locator('#manual-question-image').setInputFiles({name:'large.png',mimeType:'image/png',buffer:Buffer.alloc(5*1024*1024+1)});
 check('image >5MB rejected',(await page.locator('#manual-image-status').innerText()).includes('5 MB'));
 await page.locator('#manual-question-image').setInputFiles([]);
 await page.keyboard.press('Escape');
 check('Escape closes dialog',!await dialog.evaluate(el=>el.open));
 check('focus restored',await open.evaluate(el=>el===document.activeElement));
 const edit=page.getByRole('button',{name:'Sửa',exact:true}).first();await edit.click();
 await page.locator('.inline-edit-card').waitFor({state:'visible'});
 const editor=page.locator('.inline-edit-card');
 check('inline prompt receives focus',await editor.locator('textarea').first().evaluate(el=>el===document.activeElement));
 await editor.locator('textarea[required]').first().fill('Bản chỉnh sửa cần giữ khi có lỗi $x=2$.');
 await editor.locator('input[type=checkbox]').last().check();
 await page.route('**/questions/*/update',route=>route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({success:false,message:'Lỗi lưu mô phỏng để kiểm tra giữ nội dung.'})}));
 await editor.getByRole('button',{name:'Lưu thay đổi',exact:true}).click();
 await page.locator('[data-edit-error]').waitFor({state:'visible'});
 check('save error visible',(await page.locator('[data-edit-error]').innerText()).includes('mô phỏng'));
 check('failed save retains draft',(await editor.locator('textarea[required]').first().inputValue()).includes('Bản chỉnh sửa'));
 check('save can retry',await editor.getByRole('button',{name:'Lưu thay đổi',exact:true}).isEnabled());
 await page.unroute('**/questions/*/update');await editor.getByRole('button',{name:'Hủy chỉnh sửa'}).click();
 for(const width of [375,768,1024,1440]){
  await page.setViewportSize({width,height:900});await page.goto('http://127.0.0.1:8766/question-banks/3');await page.waitForTimeout(450);
  const geometry=await page.evaluate(()=>({body:document.documentElement.scrollWidth,width:innerWidth,coverage:document.querySelector('.bank-coverage').open}));
  check(width+' no horizontal page overflow',geometry.body<=geometry.width+1);
  check(width+' coverage responsive',geometry.coverage===(width>=1200));
  await page.screenshot({path:'/tmp/linhedu-bank-'+width+'.png',fullPage:false});
  await page.getByRole('button',{name:'Thêm câu hỏi',exact:true}).first().click();
  const bounds=await dialog.boundingBox();check(width+' dialog fits viewport',bounds.x>=-1&&bounds.width<=width+1);const inner=await dialog.locator('.bank-dialog-body').evaluate(el=>({scroll:el.scrollWidth,client:el.clientWidth}));check(width+' dialog body no horizontal overflow',inner.scroll<=inner.client+1);
  await page.screenshot({path:'/tmp/linhedu-bank-dialog-'+width+'.png',fullPage:false});
  await page.keyboard.press('Escape');
 }
 console.log('Runtime errors:',JSON.stringify(errors));check('no page runtime errors',errors.length===0);
 fs.writeFileSync('/tmp/linhedu-phase4-detail-browser.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({passed:checks.length,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
